// Exports the static site to dist/wordpress/, the folder the WordPress theme serves
// (landings/hsil-hackathon-2027/ in INT-Classic-Theme-WP). Conventions: CLAUDE.md "WordPress export".
import { execSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SOURCE_REPO = 'https://github.com/iNT-Mahidol/hsil-hackathon-2027';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'dist', 'wordpress');

// Each page: source file, output dir, the prefix its asset paths carry, its language.
const PAGES = [
  { src: 'index.html', out: '', prefix: '', lang: 'th' },
  { src: 'en/index.html', out: 'en', prefix: '../', lang: 'en' },
];

const TAG = /<[a-zA-Z][^>]*>/g;
const LANG_HREF = /^(\.\.\/)+(en\/)?$|^(\.\/)?en\/$/;

const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
const decode = (s) =>
  s.replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
export const phpString = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const escRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function fail(errors, where) {
  if (errors.length) throw new Error(`${where}:\n  - ${errors.join('\n  - ')}`);
}

export function bodyOf(html) {
  const m = html.match(/<body[^>]*>([\s\S]*)<\/body>/);
  if (!m) throw new Error('no <body> found');
  return m[1].trim();
}

// Rewrites asset paths and language links in a page's body. `exists(path)` checks 'assets/…' on disk.
export function convertBody(body, { prefix, exists = () => true }) {
  const errors = [];
  if (/<style[\s>]/i.test(body)) errors.push('inline <style> inside <body>');
  for (const tag of body.match(/<script\b[^>]*>/gi) ?? []) {
    if (!/\ssrc=/.test(tag)) errors.push(`inline <script> inside <body>: ${tag}`);
  }

  const out = body.replace(TAG, (tag) => {
    for (const name of ['src', 'href']) {
      const v = attr(tag, name);
      if (v?.startsWith('/') && !v.startsWith('//')) errors.push(`root-relative ${name}="${v}" in ${tag}`);
    }
    const lang = attr(tag, 'data-lang-link');
    const href = attr(tag, 'href');
    if (lang) {
      if (!['th', 'en'].includes(lang)) errors.push(`data-lang-link must be "th" or "en": ${tag}`);
      return tag.replace(/\shref="[^"]*"/, ` href="<?php echo esc_url( int_landing_lang_url( '${lang}' ) ); ?>"`);
    }
    const external = /^([a-z][a-z0-9+.-]*:|\/\/|#)/i.test(href ?? '');
    if (href !== undefined && !external && (LANG_HREF.test(href) || /\shreflang=/.test(tag))) {
      errors.push(`language link without data-lang-link: ${tag}`);
    }
    return tag.replace(new RegExp(`(\\s(?:src|href)=")${escRegex(prefix)}(assets/[^"]+)"`, 'g'), (_, start, path) => {
      if (!exists(path)) errors.push(`missing file ${path}`);
      return `${start}<?php echo esc_url( int_landing_asset( '${path}' ) ); ?>"`;
    });
  });
  fail(errors, 'body');
  return out;
}

export function extractMeta(html, { prefix }) {
  const head = html.match(/<head[^>]*>([\s\S]*)<\/head>/)?.[1] ?? '';
  const tags = head.match(TAG) ?? [];
  const title = head.match(/<title>([\s\S]*?)<\/title>/)?.[1];
  const description = tags.map((t) => /\sname="description"/.test(t) && attr(t, 'content')).find(Boolean);
  const fonts = tags
    .filter((t) => /^<link\b/.test(t) && attr(t, 'rel') === 'stylesheet')
    .map((t) => attr(t, 'href'))
    .find((h) => h?.startsWith('https://fonts.googleapis.com/'));
  const preload = tags
    .filter((t) => /^<link\b/.test(t) && attr(t, 'rel') === 'preload')
    .map((t) => decode(attr(t, 'href')).replace(prefix, ''));
  const errors = [];
  if (!title) errors.push('no <title>');
  if (!description) errors.push('no <meta name="description">');
  if (!fonts) errors.push('no Google Fonts stylesheet <link>');
  fail(errors, 'head');
  return { title: decode(title.trim()), description: decode(description), fonts: decode(fonts), preload };
}

export function renderMeta({ title, description, fonts, preload }, source) {
  return `<?php
/**
 * <title>, <meta name="description">, Google Fonts and preloads of ${source}. Generated by npm run export:wp.
 *
 * @package Int_Theme
 */

defined( 'ABSPATH' ) || exit;

return array(
	'title'       => ${phpString(title)},
	'description' => ${phpString(description)},
	'fonts'       => ${phpString(fonts)},
	'preload'     => array( ${preload.map(phpString).join(', ')} ),
);
`;
}

export function renderContent(body, source, sha) {
  return `<?php
defined( 'ABSPATH' ) || exit;
// Source: ${SOURCE_REPO} @ ${sha} (${source} body, verbatim except asset src values and language links).
?>
${body}
`;
}

// 'assets/…' paths referenced by a page (src/href) or by the stylesheet (url(), relative to css/).
export function assetRefs(html, prefix) {
  const re = new RegExp(`\\s(?:src|href)="${escRegex(prefix)}(assets/[^"]+)"`, 'g');
  return [...html.matchAll(re)].map((m) => m[1]);
}
export function cssAssetRefs(css) {
  return [...css.matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)/g)]
    .map((m) => m[1])
    .filter((u) => !/^(data:|https?:|\/\/|#)/.test(u))
    .map((u) => posix.normalize(posix.join('css', u)))
    .filter((p) => p.startsWith('assets/'));
}

function gitSha() {
  const sha = execSync('git rev-parse HEAD', { cwd: ROOT }).toString().trim();
  const dirty = execSync('git status --porcelain', { cwd: ROOT }).toString().trim() !== '';
  return dirty ? `${sha}-dirty` : sha;
}

function main() {
  const sha = gitSha();
  const onDisk = (p) => existsSync(join(ROOT, decodeURIComponent(p)));
  rmSync(OUT, { recursive: true, force: true });

  const assets = new Set(cssAssetRefs(readFileSync(join(ROOT, 'css/styles.css'), 'utf8')));
  for (const page of PAGES) {
    const html = readFileSync(join(ROOT, page.src), 'utf8');
    let body;
    let meta;
    try {
      body = convertBody(bodyOf(html), { prefix: page.prefix, exists: onDisk });
      meta = extractMeta(html, page);
    } catch (e) {
      throw new Error(`${page.src} ${e.message}`);
    }
    assetRefs(html, page.prefix).forEach((a) => assets.add(a));
    mkdirSync(join(OUT, page.out), { recursive: true });
    writeFileSync(join(OUT, page.out, 'content.php'), renderContent(body, page.src, sha));
    writeFileSync(join(OUT, page.out, 'meta.php'), renderMeta(meta, page.src));
  }

  for (const a of assets) {
    if (a.startsWith('assets/aw/')) throw new Error(`${a}: assets/aw/ holds the large originals; never reference it`);
    if (!onDisk(a)) throw new Error(`missing file ${a}`);
    const to = join(OUT, decodeURIComponent(a));
    mkdirSync(dirname(to), { recursive: true });
    cpSync(join(ROOT, decodeURIComponent(a)), to);
  }
  cpSync(join(ROOT, 'css'), join(OUT, 'css'), { recursive: true });
  cpSync(join(ROOT, 'js'), join(OUT, 'js'), { recursive: true });
  writeFileSync(join(OUT, 'SOURCE'), `${sha}\n`);
  console.log(`Exported to dist/wordpress/ @ ${sha} (${assets.size} assets)`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (e) {
    rmSync(OUT, { recursive: true, force: true }); // never leave a half-written export to copy
    console.error(`export:wp failed: ${e.message}`);
    process.exit(1);
  }
}
